-- ============================================================
-- 011 — Orders fulfilment (2026-06-30)
-- Link orders to the buyer's account (user_id), give them a human-friendly
-- number, and carry dispatch state: Royal Mail tracking + shipped/refunded
-- timestamps (the timestamps gate one-time emails). Idempotent. Apply after 010.
-- ============================================================

alter table public.orders
  add column if not exists user_id uuid references auth.users(id) on delete set null;
alter table public.orders
  add column if not exists tracking_number text;
alter table public.orders
  add column if not exists shipped_at timestamptz;     -- set when the shipped email goes out
alter table public.orders
  add column if not exists refunded_at timestamptz;     -- set when the refund email goes out

-- human-friendly order number (existing rows get values automatically)
alter table public.orders
  add column if not exists order_no bigint generated by default as identity;

create index if not exists idx_orders_user_id on public.orders (user_id);

-- customers read their own orders by account email OR by linked user_id
-- (a guest checkout email may differ from the account email).
drop policy if exists "customers read own orders" on public.orders;
create policy "customers read own orders"
  on public.orders for select to authenticated
  using (email = auth.email() or user_id = auth.uid());
